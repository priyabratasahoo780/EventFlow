export type Priority = 'low' | 'medium' | 'high' | 'critical';
export type TaskStatus = 'pending' | 'in_progress' | 'completed' | 'late_completed' | 'overdue' | 'cancelled' | 'pending_exit';
export type ReminderType = 'before' | 'exact' | 'daily' | 'weekly' | 'monthly' | 'yearly';

// Edge Case 2: Time-Gated Locations
// Alarm only fires if current time/day falls inside this gate
export interface LocationTimeGate {
  startHour: number;   // 0–23, e.g. 9 for 9 AM
  endHour: number;     // 0–23, e.g. 17 for 5 PM
  days: string[];      // e.g. ['Monday','Tuesday','Wednesday','Thursday','Friday']
}


export interface LocationDetails {
  latitude?: number;
  longitude?: number;
  address?: string;
}

export interface ChecklistItem {
  id: string;
  text: string;
  completed: boolean;
}

export interface LinkedContact {
  name: string;
  phone?: string;
  email?: string;
}


export interface ReminderConfig {
  id: string; // Unique ID for the reminder
  type: ReminderType;
  
  // For 'before' type
  value?: number; // e.g. 5, 10, 1
  unit?: 'minutes' | 'hours' | 'days' | 'weeks'; 

  // For 'exact', 'daily', 'weekly', 'monthly', 'yearly'
  time?: string; // "HH:mm"

  // For 'exact' and 'yearly'
  date?: string; // "YYYY-MM-DD" or "MM-DD" for yearly

  // For 'weekly'
  days?: string[]; // e.g. ["Monday", "Wednesday"]

  // For 'monthly'
  dayOfMonth?: number; // 1-31

  // Notification & Alarm preferences
  notificationPreference?: 'banner_sound' | 'banner_only' | 'silent';
  alarmPreference?: 'notification' | 'alarm' | 'both';
  snooze?: number; // snooze duration in minutes
  sound?: 'default' | 'silent' | 'custom';
  vibration?: boolean; // vibration ON/OFF

  // The actual Expo Notification identifiers generated by OS
  notificationIds?: string[];
}

export interface EventOwner {
  _id?: string;
  name?: string;
  username?: string;
  profilePhoto?: string;
  uniqueId?: string;
}

export interface Event {
  id: string;
  _id?: string;
  title: string;
  description: string;
  category: string;
  priority: Priority;
  priorityScore?: number;
  estimatedDuration?: number; // in minutes
  status: TaskStatus;
  date: string; // ISO string for the main event date
  time: string; // HH:mm for the main event time
  
  // Multiple reminders!
  reminders: ReminderConfig[];
  
  color: string;
  icon: string;
  notes: string;
  location: string;
  locationDetails?: LocationDetails;
  image?: string;
  video?: string;
  linkedContact?: LinkedContact;
  completed: boolean;
  // Edge Case Fix #7: All-day tasks have no specific deadline time.
  // When true, the task is only "overdue" after the calendar day ends (next midnight).
  isAllDay?: boolean;
  // Location Reminder Feature
  locationReminderEnabled?: boolean;
  geofenceRadius?: number;
  triggerType?: 'arrive' | 'leave';
  locationReminderTriggered?: boolean;
  checklist?: ChecklistItem[];

  // Edge Case 2: Time-Gated Locations
  locationTimeGate?: LocationTimeGate;


  // Edge Case 4: Contextual Snooze — task enters this state when user snoozes by geofence exit
  pendingExitGeofenceId?: string;

  // Edge Case 5: Critical Task — overrides phone silent mode and maxes alarm volume
  isCritical?: boolean;


  
  // Timestamps
  startedAt?: string;
  completedAt?: string;
  createdAt: string;
  updatedAt: string;

  // Backend sync properties
  ownerId?: string | EventOwner;
  visibility?: 'onlyMe' | 'friends' | 'selectedFriends';
  sharedWith?: string[]; // Array of user IDs
}

export interface EventFilters {
  searchQuery: string;
  category: string;
  status: 'all' | 'today' | 'pending' | 'in_progress' | 'completed' | 'overdue';
  timeframe: 'all' | 'today' | 'tomorrow' | 'this_week' | 'this_month';
  priority: 'all' | 'critical' | 'high' | 'medium' | 'low';
}
